#!/usr/bin/env python3
"""The single source of LXRXXL's plugin parameters: writes params.json (mpc-vst-plugins) and src/param_ids.h.

MPC stores a project's values by parameter index, so parameters are only ever appended to this list."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

FADERS = ["DRUM1", "DRUM2", "DRUM3", "SNARE", "CLP/CYM", "HIHATS", "VOLUME"]
BUTTONS = [("shift", "SHIFT"), ("play", "PLAY"), ("rec", "REC"), ("copy", "COPY/CLR"), ("voice", "VOICE"),
           ("perf", "PERF"), ("load", "LOAD"), ("save", "SAVE"), ("osc", "OSC"), ("aeg", "AEG"), ("mod", "MOD"),
           ("fm", "FM"), ("click", "CLICK"), ("filter", "FILTER"), ("lfo", "LFO"), ("mix", "MIX"),
           ("barl", "BAR <"), ("barr", "BAR >"),
           ("v1", "DRUM1"), ("v2", "DRUM2"), ("v3", "DRUM3"), ("v4", "SNARE"), ("v5", "CLP/CYM"), ("v6", "CL HH"),
           ("v7", "OP HH")] + \
          [("s%d" % (i + 1), n) for i, n in enumerate(["DRUM1", "DRUM2", "DRUM3", "SNARE", "CLP/CYM", "CL HH", "OP HH",
                                                       "KIT", "MORPH", "SONG", "PROJECT", "CONFIG", "RELOAD",
                                                       "LAST STEP", "FX", "PATTERN"])] + \
          [("enc", "DATA PUSH")]


def params():
    out = []
    for i, n in enumerate(FADERS):
        out.append({"key": "fader%d" % (i + 1), "name": n, "min": 0, "max": 1, "default": 0.8 if i == 6 else 1.0})
    out.append({"key": "data", "name": "DATA", "min": 0, "max": 1, "default": 0.5})
    for i in range(4):
        out.append({"key": "pot%d" % (i + 1), "name": "POT %d" % (i + 1), "min": 0, "max": 1, "default": 0.5,
                    "dynamic_display": True})   # shows the value it edits (printed in the pot's white centre)
    for i in range(8):
        out.append({"key": "slot%d" % (i + 1), "name": "-", "min": 0, "max": 1, "default": 0,
                    "dynamic_name": True, "dynamic_display": True})
    for i in range(8):
        out.append({"key": "slot%d_used" % (i + 1), "name": "slot %d shown" % (i + 1), "options": ["off", "on"],
                    "default": 0})
    out.append({"key": "pots", "name": "POTS", "options": ["1-4", "5-8"], "default": 0})
    out.append({"key": "lcd1", "name": "LCD 1", "display": "string", "min": 0, "max": 1, "default": 0})
    out.append({"key": "lcd2", "name": "LCD 2", "display": "string", "min": 0, "max": 1, "default": 0})
    for k, n in BUTTONS:
        out.append({"key": k, "name": n, "display": "string", "min": 0, "max": 1, "default": 0})
    # the mod: the voice randomizer (green) and the step randomizer (yellow), each a key and an amount knob
    pcts = ["%d%%" % (10 * i) for i in range(11)]
    out.append({"key": "rnd", "name": "VOICE RANDOM", "display": "string", "min": 0, "max": 1, "default": 0})
    out.append({"key": "rnd_amt", "name": "VOICE RND AMT", "options": pcts, "default": 5})
    out.append({"key": "srnd", "name": "STEP RANDOM", "display": "string", "min": 0, "max": 1, "default": 0})
    out.append({"key": "srnd_amt", "name": "STEP RND AMT", "options": pcts, "default": 5})
    out.append({"key": "reset", "name": "RESET", "display": "string", "min": 0, "max": 1, "default": 0})
    return out


def main():
    ps = params()
    json.dump({"params": ps}, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    lines = ["/* GENERATED by tools/gen_params.py: do not edit. The plugin's parameters, in VST index order. */",
             "#pragma once", "enum {"]
    for i, p in enumerate(ps):
        lines.append("    P_%s = %d," % (p["key"].upper(), i))
    lines += ["    P_COUNT = %d" % len(ps), "};",
              "static const char *const PARAM_KEYS[P_COUNT] = {" + ", ".join('"%s"' % p["key"] for p in ps) + "};",
              "#define P_FIRST_BUTTON P_SHIFT", "#define P_NUM_BUTTONS %d" % len(BUTTONS)]
    open(os.path.join(ROOT, "src/param_ids.h"), "w").write("\n".join(lines) + "\n")
    print("params: %d (%d buttons)" % (len(ps), len(BUTTONS)))


if __name__ == "__main__":
    main()
