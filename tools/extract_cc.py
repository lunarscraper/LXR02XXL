#!/usr/bin/env python3
"""Cut the LXR-02 firmware's parameter handler out of its MIDI parser, verbatim.

    python3 tools/extract_cc.py   -> src/lxr/cc_handler.inc

midiParser_ccHandler() in Core/MIDI/MidiParser.c is where every sound parameter (0-127 as a CC, 128+ as the firmware's
second CC page) is turned into DSP state. LXRXXL compiles exactly that code; the rest of the file (UART/USB parsing,
MTC, routing) belongs to the hardware and is not used. The cut runs from calcPitchModAmount() to the end of the handler.
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "third_party/lxr02open/Core/MIDI/MidiParser.c"), encoding="latin-1").read().split("\n")
start = next(i for i, l in enumerate(src) if l.startswith("static inline float calcPitchModAmount"))
start -= 1   # its comment line
end = next(i for i, l in enumerate(src) if l.startswith("void midiParser_checkMtc()"))
while not src[end - 1].startswith("}"):
    end -= 1
body = src[start:end]
# the parser's own globals that the handler uses live in lxr_params.c; drop their definitions from the cut
skip = ("uint8_t midi_MidiChannels[8];", "uint8_t midi_NoteOverride[7];", "MidiMsg midiMsg_tmp;", "static uint8_t parserState")
out = []
for l in body:
    if l.startswith(skip):
        out.append("/* LXRXXL: defined in lxr_params.c -- " + l.strip() + " */")
        continue
    out.append(l)
hdr = ["/* GENERATED by tools/extract_cc.py from third_party/lxr02open/Core/MIDI/MidiParser.c (lines %d-%d): do not edit."
       % (start + 1, end), " * The LXR-02 firmware's parameter handler, verbatim (LXR licence, see third_party/lxr02open/LICENSE). */"]
open(os.path.join(ROOT, "src/lxr/cc_handler.inc"), "w").write("\n".join(hdr + out) + "\n")
print("cc_handler.inc: lines %d-%d" % (start + 1, end))

# --- the menu's parameter tables (menu.c), verbatim: value types and names, used for the screen's value text ---
menu = open(os.path.join(ROOT, "third_party/lxr02open/Core/Menu/menu.c.ref"), encoding="latin-1").read().split("\n")
def cut(first_prefix):
    s = next(i for i, l in enumerate(menu) if l.startswith(first_prefix))
    e = next(i for i in range(s, len(menu)) if menu[i].startswith("};"))
    return menu[s:e + 1], s + 1, e + 1
dt, a, b = cut("const enum Datatypes parameter_dtypes[NUM_PARAMS]")
vn, c, d = cut("static const Name valueNames[NUM_NAMES]")
open(os.path.join(ROOT, "src/lxr/menu_tables.inc"), "w").write("\n".join(
    ["/* GENERATED by tools/extract_cc.py from the LXR02Open menu.c (lines %d-%d, %d-%d): do not edit. */" % (a, b, c, d)]
    + dt + [""] + vn) + "\n")
print("menu_tables.inc: lines %d-%d, %d-%d" % (a, b, c, d))
